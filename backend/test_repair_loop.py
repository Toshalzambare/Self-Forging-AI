import asyncio
from agents.state import AgentState
from agents.graph import verify_node, repair_node

async def main():
    print("--- Test 3: Sandbox & Repair Loop (Direct Node Testing) ---")
    
    # 1. Provide an intentionally broken function
    buggy_code = """
def add_numbers(a: int, b: int) -> int:
    # Intentionally subtracting instead of adding!
    return a - b
"""
    # 2. Provide tests that will definitely fail on the buggy code
    tests = """
import pytest
from generated_tool import add_numbers

def test_add_numbers():
    assert add_numbers(2, 3) == 5
"""
    
    state = {
        "task": "A tool that adds two numbers",
        "missing_capability": "Add two numbers",
        "generated_code": buggy_code,
        "adversarial_tests": tests,
        "sandbox_results": "",
        "tests_passed": False,
        "repair_attempts": 0
    }
    
    print("\n[1] Running Verify Node (Sandbox Execution)...")
    verify_result = await verify_node(state)
    state.update(verify_result)
    
    print("\nSandbox Execution Results:")
    print(f"Tests Passed: {state['tests_passed']}")
    print("Logs written to test_repair_results.md")
    
    if not state['tests_passed']:
        print("\n[2] Tests failed! Triggering Repair Node...")
        repair_result = await repair_node(state)
        state.update(repair_result)
        
        print("\nRepair Node Results:")
        print(f"Repair Attempts: {state['repair_attempts']}")
        print("\nFixed Code generated by Repair Node written to test_repair_results.md")
        
        # Optionally, verify again to see if it passes!
        print("\n[3] Running Verify Node again on the repaired code...")
        verify_result_2 = await verify_node(state)
        state.update(verify_result_2)
        print(f"\nFinal Tests Passed: {state['tests_passed']}")
        
    with open("test_repair_results.md", "w", encoding="utf-8") as f:
        f.write("# LangGraph Sandbox & Repair Loop Results\n\n")
        f.write("## Initial Buggy Code\n```python\n" + buggy_code + "\n```\n")
        f.write("## Sandbox Error Trace\n```\n" + state.get('sandbox_results', '') + "\n```\n")
        f.write("## Repaired Code\n```python\n" + state.get('generated_code', '') + "\n```\n")
        f.write(f"## Final Status\nTests Passed: {state['tests_passed']}\nRepair Attempts: {state['repair_attempts']}\n")

if __name__ == "__main__":
    asyncio.run(main())
